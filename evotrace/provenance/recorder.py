"""Provenance recorder and overhead calculator."""

from __future__ import annotations
import json
import logging
from typing import Any, Dict, List, Optional
from pymongo.database import Database

from evotrace.config import Config
from evotrace.database import get_db
from evotrace.models import ProvenanceRecord

logger = logging.getLogger(__name__)


def calculate_provenance_storage_bytes(provenance_data: Dict[str, Any]) -> int:
    """Measure the byte size of a serialized provenance document."""
    try:
        serialized = json.dumps(provenance_data, default=str)
        return len(serialized.encode("utf-8"))
    except Exception:
        return 0


def get_provenance_by_id(provenance_id: str, db: Optional[Database] = None) -> Optional[Dict[str, Any]]:
    """Retrieve a single provenance record by its ID."""
    db = get_db() if db is None else db
    col = db[Config.COLLECTION_PROVENANCE]
    doc = col.find_one({"provenance_id": provenance_id})
    if doc and "_id" in doc:
        doc["_id"] = str(doc["_id"])
    return doc


def get_provenance_by_operation_id(operation_id: str, db: Optional[Database] = None) -> Optional[Dict[str, Any]]:
    """Retrieve the primary provenance record generated by an evolution operation."""
    db = get_db() if db is None else db
    col = db[Config.COLLECTION_PROVENANCE]
    doc = col.find_one({"operation_id": operation_id, "is_recovery": False})
    if doc and "_id" in doc:
        doc["_id"] = str(doc["_id"])
    return doc


def get_recovery_audit_for_operation(operation_id: str, db: Optional[Database] = None) -> List[Dict[str, Any]]:
    """Retrieve any recovery provenance records associated with the target operation."""
    db = get_db() if db is None else db
    col = db[Config.COLLECTION_PROVENANCE]
    cursor = col.find({"recovers_operation_id": operation_id, "is_recovery": True}).sort("timestamp", -1)
    results = []
    for doc in cursor:
        if "_id" in doc:
            doc["_id"] = str(doc["_id"])
        results.append(doc)
    return results
